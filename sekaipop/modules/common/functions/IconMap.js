function candidates(name, filled, style) {
    let entry = map[name]
    if (entry === undefined)
        entry = String(name).replace(/_/g, "-")

    let first = filled ? "bold" : style
    const bar = entry.indexOf("|")
    if (bar >= 0) {
        first = entry.slice(bar + 1) === "o" ? style : "bold"
        entry = entry.slice(0, bar)
    }

    const out = []
    for (const s of [first, "outline", "bold"]) {
        const p = "icons/" + s + "/" + entry + ".svg"
        if (out.indexOf(p) < 0)
            out.push(p)
    }
    return out
}
